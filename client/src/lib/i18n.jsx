const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('miv.lang') || 'fr');

  useEffect(() => {
    localStorage.setItem('miv.lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback((key) => DICT[lang][key] ?? DICT.fr[key] ?? key, [lang]);
  /** Picks the right column of a bilingual record: pick(course, 'title') */
  const pick = useCallback((row, field) => row?.[`${field}_${lang}`] ?? row?.[`${field}_fr`] ?? '', [lang]);

  const value = useMemo(
    () => ({ lang, setLang, toggle: () => setLang((l) => (l === 'fr' ? 'en' : 'fr')), t, pick }),
    [lang, t, pick]
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error('useLang must be used inside <LangProvider>');
  return ctx;
}
